begin;

create type public.product_badge as enum ('new', 'sale', 'popular');
create type public.store_role as enum ('owner', 'admin', 'catalog_manager', 'order_manager', 'marketing_manager');
create type public.order_status as enum ('pending', 'confirmed', 'processing', 'shipped', 'delivered', 'cancelled', 'refunded');
create type public.payment_method as enum ('cash_on_delivery', 'online_card');
create type public.payment_status as enum ('pending', 'paid', 'failed', 'refunded');
create type public.promotion_discount_type as enum ('percentage', 'fixed_amount');

create function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create table public.categories (
  id bigint generated by default as identity primary key,
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  name_translations jsonb not null default '{}'::jsonb check (jsonb_typeof(name_translations) = 'object'),
  description_translations jsonb not null default '{}'::jsonb check (jsonb_typeof(description_translations) = 'object'),
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.products (
  slug text primary key check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  category_slug text not null references public.categories(slug) on update cascade on delete restrict,
  brand text not null,
  name_translations jsonb not null default '{}'::jsonb check (jsonb_typeof(name_translations) = 'object'),
  description_translations jsonb not null default '{}'::jsonb check (jsonb_typeof(description_translations) = 'object'),
  price numeric(12, 2) not null check (price >= 0),
  compare_at_price numeric(12, 2) check (compare_at_price is null or compare_at_price >= price),
  currency char(3) not null default 'SAR',
  rating numeric(2, 1) not null default 0 check (rating between 0 and 5),
  review_count integer not null default 0 check (review_count >= 0),
  badge public.product_badge,
  in_stock boolean not null default true,
  is_active boolean not null default false,
  is_featured boolean not null default false,
  sort_order integer not null default 0,
  external_image_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.product_features (
  product_slug text not null references public.products(slug) on update cascade on delete cascade,
  language_code text not null check (language_code in ('en', 'fr', 'es', 'zh', 'ar')),
  position smallint not null check (position >= 0),
  content text not null,
  primary key (product_slug, language_code, position)
);

create table public.product_variants (
  id uuid primary key default gen_random_uuid(),
  variant_key text not null unique,
  product_slug text not null references public.products(slug) on update cascade on delete cascade,
  option_group text not null check (option_group in ('storage', 'size', 'color')),
  option_value text not null,
  option_label_translations jsonb not null default '{}'::jsonb check (jsonb_typeof(option_label_translations) = 'object'),
  sku text unique,
  price_adjustment numeric(12, 2) not null default 0,
  stock_quantity integer check (stock_quantity is null or stock_quantity >= 0),
  is_active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.product_images (
  id uuid primary key default gen_random_uuid(),
  product_slug text not null references public.products(slug) on update cascade on delete cascade,
  image_url text,
  storage_path text,
  alt_translations jsonb not null default '{}'::jsonb check (jsonb_typeof(alt_translations) = 'object'),
  is_primary boolean not null default false,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  constraint product_images_one_source check (num_nonnulls(image_url, storage_path) = 1),
  unique (product_slug, sort_order)
);

create table public.promotions (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  title_translations jsonb not null default '{}'::jsonb check (jsonb_typeof(title_translations) = 'object'),
  description_translations jsonb not null default '{}'::jsonb check (jsonb_typeof(description_translations) = 'object'),
  discount_type public.promotion_discount_type not null,
  discount_value numeric(12, 2) not null check (discount_value > 0),
  coupon_code text unique,
  minimum_order numeric(12, 2) not null default 0 check (minimum_order >= 0),
  starts_at timestamptz,
  ends_at timestamptz,
  is_active boolean not null default false,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint promotions_date_order check (starts_at is null or ends_at is null or ends_at > starts_at)
);

create table public.banners (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  placement text not null check (placement in ('home_hero', 'home_promo', 'mobile_promo', 'category')),
  title_translations jsonb not null default '{}'::jsonb check (jsonb_typeof(title_translations) = 'object'),
  description_translations jsonb not null default '{}'::jsonb check (jsonb_typeof(description_translations) = 'object'),
  button_translations jsonb not null default '{}'::jsonb check (jsonb_typeof(button_translations) = 'object'),
  image_path text,
  mobile_image_path text,
  destination_url text,
  starts_at timestamptz,
  ends_at timestamptz,
  sort_order integer not null default 0,
  is_active boolean not null default false,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint banners_date_order check (starts_at is null or ends_at is null or ends_at > starts_at)
);

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  phone text,
  preferred_language text not null default 'en' check (preferred_language in ('en', 'fr', 'es', 'zh', 'ar')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.staff_roles (
  user_id uuid not null references auth.users(id) on delete cascade,
  role public.store_role not null,
  assigned_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  primary key (user_id, role)
);

create function public.has_store_role(allowed_roles public.store_role[])
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.staff_roles
    where user_id = (select auth.uid())
      and role = any(allowed_roles)
  );
$$;

grant execute on function public.has_store_role(public.store_role[]) to anon, authenticated;

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number text not null unique,
  user_id uuid references auth.users(id) on delete set null,
  customer_name text not null,
  customer_email text,
  customer_phone text not null,
  status public.order_status not null default 'pending',
  payment_method public.payment_method not null default 'cash_on_delivery',
  payment_status public.payment_status not null default 'pending',
  currency char(3) not null default 'SAR',
  subtotal numeric(12, 2) not null default 0 check (subtotal >= 0),
  discount_total numeric(12, 2) not null default 0 check (discount_total >= 0),
  shipping_total numeric(12, 2) not null default 0 check (shipping_total >= 0),
  total numeric(12, 2) not null default 0 check (total >= 0),
  shipping_address jsonb not null default '{}'::jsonb check (jsonb_typeof(shipping_address) = 'object'),
  customer_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_slug text references public.products(slug) on update cascade on delete set null,
  product_name_translations jsonb not null default '{}'::jsonb check (jsonb_typeof(product_name_translations) = 'object'),
  variant_label_translations jsonb not null default '{}'::jsonb check (jsonb_typeof(variant_label_translations) = 'object'),
  sku text,
  quantity integer not null check (quantity > 0),
  unit_price numeric(12, 2) not null check (unit_price >= 0),
  line_total numeric(12, 2) not null check (line_total >= 0),
  created_at timestamptz not null default now()
);

create table public.order_events (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  from_status public.order_status,
  to_status public.order_status not null,
  note text,
  changed_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table public.store_settings (
  setting_key text primary key,
  setting_value jsonb not null default '{}'::jsonb check (jsonb_typeof(setting_value) = 'object'),
  description text,
  is_public boolean not null default false,
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now()
);

