function renderManagedCategoryBanner() {
  const banner = (window.RUQO_STORE_BANNERS || []).find((item) => item.placement === "category");
  const container = document.querySelector("[data-desktop-banner]");
  if (!banner || !container) return;
  const localized = (field, fallback = "") => banner[field]?.[language] || banner[field]?.en || fallback;
  container.querySelector(".banner-title").textContent = localized("title_translations");
  container.querySelector(".banner-subtitle").textContent = localized("description_translations");
  const image = container.querySelector(".banner-img");
  if (image && banner.image_url) {
    image.src = banner.image_url;
    image.alt = localized("title_translations", "Store campaign");
  }
  const button = container.querySelector(".banner-btn");
  if (button && banner.destination_url) {
    const link = document.createElement("a");
    link.className = button.className;
    link.href = banner.destination_url;
    link.textContent = localized("button_translations", language === "ar" ? "اكتشف" : "Explore");
    button.replaceWith(link);
  } else if (button) {
    button.textContent = localized("button_translations", button.textContent);
  }
}

function filteredProducts() {
  const query = ui.search.value.trim().toLocaleLowerCase();
  const cats = $$("[data-category-filter]:checked").map((input) => input.value);
  const min = Number(ui.min.value) || 0;
  const max = Number(ui.max.value) || 10000;
  const currency = window.NoursStore?.getCurrency() || "USD";
  const minInSar = window.NoursStore?.convertCurrency(min, currency, "SAR") ?? min;
  const maxInSar = window.NoursStore?.convertCurrency(max, currency, "SAR") ?? max;
  const rating = Number($("[data-rating-filter]:checked").value);
  const results = products.filter((product) => {
    const localized = localizeProduct(product);
    const searchText =
      `${localized.name} ${product.brand} ${localized.description[language]} ${product.description.en} ${product.description.ar}`.toLocaleLowerCase();
    return (
      (!query || searchText.includes(query)) &&
      (!cats.length || cats.includes(product.category)) &&
      product.price >= min &&
      product.price >= minInSar &&
      product.price <= maxInSar &&
      product.rating >= rating &&
      (!dealsOnly || (product.oldPrice && product.oldPrice > product.price)) &&
      (!ui.stock.checked || product.stock)
    );
  });
  const comparators = {
    featured: (a, b) =>
      Number(b.badge === "popular") - Number(a.badge === "popular") ||
      b.rating - a.rating,
    newest: (a, b) => b.newest - a.newest,
    "price-asc": (a, b) => a.price - b.price,
    "price-asc": (a, b) =>
      (window.NoursStore?.convertCurrency(a.price, "SAR", currency) ?? a.price)
      - (window.NoursStore?.convertCurrency(b.price, "SAR", currency) ?? b.price),
    "price-desc": (a, b) =>
      (window.NoursStore?.convertCurrency(b.price, "SAR", currency) ?? b.price)
      - (window.NoursStore?.convertCurrency(a.price, "SAR", currency) ?? a.price),
    rating: (a, b) => b.rating - a.rating || b.reviews - a.reviews,
  };
  return results.sort(comparators[ui.sort.value] || comparators.featured);
}

